import os
import json
import pandas as pd

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OUT_DIR    = os.path.join(SCRIPT_DIR, "ieee_results")
OUTPUT_MD  = os.path.join(OUT_DIR, "all_results_consolidated.md")

csv_files = [f for f in os.listdir(OUT_DIR) if f.endswith(".csv")]
json_files = [f for f in os.listdir(OUT_DIR) if f.endswith(".json")]

with open(OUTPUT_MD, "w", encoding="utf-8") as f:
    f.write("# EduGuard AI — Consolidated IEEE Access Results\n\n")
    f.write("This document contains all experimental results generated by the pipeline.\n\n")
    
    f.write("## 1. CSV Data Tables\n\n")
    for csv in sorted(csv_files):
        path = os.path.join(OUT_DIR, csv)
        try:
            df = pd.read_csv(path)
            f.write(f"### {csv}\n\n")
            f.write(df.to_markdown(index=False))
            f.write("\n\n")
        except Exception as e:
            f.write(f"Error reading {csv}: {e}\n\n")

    f.write("## 2. JSON Metrics\n\n")
    for jf in sorted(json_files):
        path = os.path.join(OUT_DIR, jf)
        try:
            with open(path, "r", encoding="utf-8") as jfile:
                data = json.load(jfile)
            f.write(f"### {jf}\n\n")
            f.write("```json\n")
            f.write(json.dumps(data, indent=2))
            f.write("\n```\n\n")
        except Exception as e:
            f.write(f"Error reading {jf}: {e}\n\n")

print(f"Consolidated results saved to {OUTPUT_MD}")
